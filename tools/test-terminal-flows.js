const assert = require('node:assert/strict');
const { LogBuffer, formatUptime, formatLog } = require('../data/js/terminal.js');

const logs = new LogBuffer(3);
const packet = (sequence, msg, level = 'info') => ({ logBootId: 'boot-a', sequence, uptimeMs: sequence * 1000, core: 1, msg, level });
logs.add(packet(1, 'Light sensor ready.'));
logs.add(packet(2, 'Light sensor ready.'));
assert.equal(logs.entries.length, 1);
assert.equal(logs.entries[0].count, 2);
assert.equal(logs.entries[0].uptimeMs, 2000);
assert.equal(logs.add(packet(2, 'Light sensor ready.')), false, 'backlog replay cannot count the same event twice');
logs.add(packet(3, '<script>broken probe</script>', 'warn'));
logs.add(packet(4, 'Cloud request failed.', 'error'));
assert.equal(logs.matching('issues', '').length, 2);
assert.equal(logs.matching('all', 'CLOUD').length, 1);
assert.equal(logs.matching('all', 'not present').length, 0);
assert.equal(logs.entries[1].msg, '<script>broken probe</script>', 'messages remain plain text for safe DOM rendering');
assert.match(formatLog(logs.entries[0]), /00:00:02.*Info.*Sensors.*repeated 2 times/);
logs.add({ ...packet(1, 'Light sensor ready.'), logBootId: 'boot-b' });
assert.equal(logs.entries.length, 3, 'retained rows stay bounded');
assert.equal(logs.entries.at(-1).count, 1, 'a new boot cannot merge with the preceding boot');
for (let i = 5; i < 500; i++) logs.add(packet(i, 'Repeated failure.', 'error'));
assert.ok(logs.seen.size <= logs.limit * 4, 'replay identity cache also stays bounded');
assert.equal(formatUptime(0), '00:00:00');
assert.equal(formatUptime(90061000), '25:01:01', 'device uptime does not wrap at one day');
assert.equal(formatUptime(null), '—');
logs.clear();
assert.equal(logs.entries.length, 0);
assert.equal(logs.seen.size, 0);
const reordered = new LogBuffer(10);
reordered.add(packet(3, 'Third message.'));
reordered.add(packet(1, 'Repeated first message.'));
reordered.add(packet(2, 'Repeated first message.'));
assert.equal(reordered.entries[0].count, 2, 'older replay is ordered before live entries');
assert.equal(reordered.entries[1].msg, 'Third message.');
console.log('Terminal grouping, replay deduplication, filtering, plain-text copy, uptime, and bounded retention passed.');
